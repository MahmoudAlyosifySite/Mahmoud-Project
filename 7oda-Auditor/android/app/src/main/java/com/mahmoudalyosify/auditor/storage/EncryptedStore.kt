package com.mahmoudalyosify.auditor.storage

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import com.mahmoudalyosify.auditor.core.Recording
import com.mahmoudalyosify.auditor.core.RecordingCoding
import java.io.File
import java.io.IOException
import java.security.KeyStore
import java.util.UUID
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Encrypts and decrypts whole files. */
interface Sealer {
    fun seal(plain: ByteArray): ByteArray
    fun open(sealed: ByteArray): ByteArray
}

/**
 * AES-256-GCM. File layout: 12-byte IV, then ciphertext with the 16-byte tag appended.
 * The IV is generated by the cipher (Android Keystore keys require randomized encryption).
 */
class AesGcmSealer(private val key: () -> SecretKey) : Sealer {
    override fun seal(plain: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        val iv = cipher.iv
        require(iv.size == IV_BYTES) { "Unexpected IV length ${iv.size}" }
        return iv + cipher.doFinal(plain)
    }

    override fun open(sealed: ByteArray): ByteArray {
        if (sealed.size < IV_BYTES + TAG_BYTES) throw IOException("Encrypted file is too short")
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BYTES * 8, sealed, 0, IV_BYTES))
        return cipher.doFinal(sealed, IV_BYTES, sealed.size - IV_BYTES)
    }

    companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val IV_BYTES = 12
        const val TAG_BYTES = 16
    }
}

/** A 256-bit AES key that never leaves the Android Keystore. */
object KeystoreKeyProvider {
    private const val PROVIDER = "AndroidKeyStore"
    const val ALIAS = "7oda-auditor-store-v1"

    @Volatile private var cached: SecretKey? = null

    @Synchronized
    fun key(): SecretKey {
        cached?.let { return it }
        val keyStore = KeyStore.getInstance(PROVIDER).apply { load(null) }
        val existing = keyStore.getKey(ALIAS, null) as? SecretKey
        val key = existing ?: run {
            val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
            val spec = KeyGenParameterSpec.Builder(
                ALIAS, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setRandomizedEncryptionRequired(true)
                .build()
            generator.init(spec)
            generator.generateKey()
        }
        cached = key
        return key
    }
}

/**
 * Every file of the app, AES-GCM encrypted, under `filesDir/auditor`:
 * people.json, samples.json, embeddings.json, calibration.json, settings.json, checks.json
 * and recordings/<uuid>.json (raw recordings, kept so features can be recomputed).
 */
class EncryptedStore(val directory: File, private val sealer: Sealer) {
    companion object {
        const val peopleFile = "people.json"
        const val samplesFile = "samples.json"
        const val embeddingsFile = "embeddings.json"
        const val calibrationFile = "calibration.json"
        const val settingsFile = "settings.json"
        const val checksFile = "checks.json"
        private const val recordingsFolder = "recordings"

        fun defaultDirectory(context: Context): File = File(context.filesDir, "auditor")

        /** The real store: Keystore-keyed AES-GCM. */
        fun live(context: Context): EncryptedStore =
            EncryptedStore(defaultDirectory(context), AesGcmSealer { KeystoreKeyProvider.key() })
    }

    private val recordingsDir = File(directory, recordingsFolder)

    init {
        if (!recordingsDir.isDirectory && !recordingsDir.mkdirs()) {
            throw IOException("Could not create ${recordingsDir.path}")
        }
    }

    // Plain text files

    /** Decrypted text of `name`, or null when the file does not exist. */
    fun readText(name: String): String? {
        val file = File(directory, name)
        if (!file.exists()) return null
        return String(sealer.open(file.readBytes()), Charsets.UTF_8)
    }

    fun writeText(name: String, text: String) = writeAtomically(File(directory, name), text)

    fun delete(name: String) {
        File(directory, name).delete()
    }

    // Recordings

    private fun recordingFile(id: UUID) = File(recordingsDir, id.toString().uppercase() + ".json")

    fun writeRecording(recording: Recording) =
        writeAtomically(recordingFile(recording.id), RecordingCoding.encode(recording))

    fun readRecording(id: UUID): Recording? {
        val file = recordingFile(id)
        if (!file.exists()) return null
        return RecordingCoding.decodeRecording(String(sealer.open(file.readBytes()), Charsets.UTF_8))
    }

    fun deleteRecording(id: UUID) {
        recordingFile(id).delete()
    }

    fun recordingIDs(): List<UUID> =
        (recordingsDir.listFiles() ?: emptyArray())
            .filter { it.isFile && it.name.endsWith(".json") }
            .mapNotNull { runCatching { UUID.fromString(it.name.removeSuffix(".json")) }.getOrNull() }

    /** Every readable recording, oldest first. */
    fun allRecordings(): List<Recording> =
        recordingIDs().mapNotNull { id -> runCatching { readRecording(id) }.getOrNull() }
            .sortedWith(compareBy<Recording>({ it.createdAt }, { it.id.toString() }))

    /** Removes every file of the app (the Keystore key stays). */
    fun deleteAll() {
        directory.listFiles()?.forEach { it.deleteRecursively() }
        if (!recordingsDir.isDirectory && !recordingsDir.mkdirs()) {
            throw IOException("Could not recreate ${recordingsDir.path}")
        }
    }

    private fun writeAtomically(file: File, text: String) {
        val sealed = sealer.seal(text.toByteArray(Charsets.UTF_8))
        val tmp = File(file.parentFile, file.name + ".tmp")
        tmp.writeBytes(sealed)
        if (!tmp.renameTo(file)) {
            file.delete()
            if (!tmp.renameTo(file)) throw IOException("Could not write ${file.name}")
        }
    }
}
