"""Experiment 4: long-form text (venv /tmp/ba/venvs/eval, CPU). -> BA/eval/results/long_form.json, .md

Texts: texts/long_v2.jsonl (24 new passages, 8 per language, written after the engine was frozen and never used for
tuning), each spoken by 2 voices per language (synth_paper.py long_ba / long_voxcpm2). Systems: BA (engine with
chunking, per-chunk checks and retries) and plain VoxCPM2 (the whole passage in one call, as in the bake-off).

Per language and system: failure share (bake-off rule F1-F4), error (CER for Egyptian, WER for English and French),
ECAPA similarity, Egyptian share under both classifiers (Egyptian only), DNSMOS, audio length, chunks and retries.
Two-way bootstrap CIs (texts x voices; with 2 voices the voice dimension adds little) and paired BA - VoxCPM2
differences on the same passage-voice cells (paper_common.py).

Run: /tmp/ba/venvs/eval/bin/python BA/eval/scripts/long_form.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from paper_common import RESULTS, engine_rows, attach_dialect, two_way_bootstrap, paired, ci, dump

SYSTEMS = {"ba": "p_long_ba", "voxcpm2": "p_long_voxcpm2"}
KEYS = ["failed", "err", "sim_ecapa", "c1", "c2", "mos_p808", "audio_sec"]


def rows_for(exp, system):
    rows = attach_dialect(engine_rows(exp, system))
    meta = {}
    import json
    with open(f"/home/jovyan/ba-work/engine/{exp}/meta.jsonl") as f:
        for line in f:
            m = json.loads(line)
            meta[m["utt_id"]] = m
    for r in rows:
        m = meta.get(r["utt_id"], {})
        r["audio_sec"] = m.get("audio_sec")
        r["n_chunks"] = m.get("n_chunks")
        r["n_retries"] = m.get("n_retries")
    return rows


def main():
    data = {s: rows_for(e, s) for s, e in SYSTEMS.items() if os.path.exists(f"/home/jovyan/ba-work/engine/{e}/scores.jsonl")}
    out = {"design": __doc__, "systems": {}, "paired_ba_minus_voxcpm2": {}}
    for s, rows in data.items():
        out["systems"][s] = {}
        for lang in ["arz", "en", "fr"]:
            rl = [r for r in rows if r["lang"] == lang]
            if not rl:
                continue
            res = {"n": len(rl)}
            for k in KEYS:
                vals = [r.get(k) for r in rl]
                if any(v is None for v in vals):
                    continue
                res[k] = two_way_bootstrap(vals, [r["text_id"] for r in rl], [r["voice_id"] for r in rl])
            if s == "ba":
                res["chunks_mean"] = float(np.mean([r["n_chunks"] or 1 for r in rl]))
                res["retries_total"] = int(sum(r["n_retries"] or 0 for r in rl))
            out["systems"][s][lang] = res
    if len(data) == 2:
        for lang in ["arz", "en", "fr"]:
            a = [r for r in data["ba"] if r["lang"] == lang]
            b = [r for r in data["voxcpm2"] if r["lang"] == lang]
            out["paired_ba_minus_voxcpm2"][lang] = {k: paired(a, b, k, binary=k in ("failed", "c1", "c2"))
                                                     for k in KEYS if k != "audio_sec" and all(r.get(k) is not None for r in a + b)}
    out["command"] = "/tmp/ba/venvs/eval/bin/python BA/eval/scripts/long_form.py"
    dump(out, f"{RESULTS}/long_form.json")
    lines = ["# Long-form text (24 new passages x 2 voices per language)", "",
             "Generated by `BA/eval/scripts/long_form.py` from `long_form.json`. 95% two-way bootstrap CIs.", "",
             "| system | lang | n | fail | CER/WER | ECAPA | Egy clf 1 | Egy clf 2 | DNSMOS | audio s |", "|---|---|---|---|---|---|---|---|---|---|"]
    for s, d in out["systems"].items():
        for lang, r in d.items():
            lines.append(f"| {s} | {lang} | {r['n']} | " + " | ".join(ci(r.get(k)) for k in KEYS) + " |")
    lines += ["", "Paired BA - VoxCPM2 [95% CI] (bootstrap p):", ""]
    for lang, d in out["paired_ba_minus_voxcpm2"].items():
        for k, t in d.items():
            if t:
                lines.append(f"- {lang} {k}: {t['diff']:+.4f} [{t['ci_lo']:+.4f}, {t['ci_hi']:+.4f}] (p {t['p_bootstrap']})")
    with open(f"{RESULTS}/long_form.md", "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
