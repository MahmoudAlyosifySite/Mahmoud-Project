@pytest.mark.parametrize("src,expected", CASES)
def test_egyptian(src, expected):
    assert arz.normalize(src) == expected


def test_case_count():
    assert len(CASES) >= 40


def test_no_digits_left():
    import re
    for src, _ in CASES:
        assert not re.search(r"[0-9٠-٩]", arz.normalize(src)), src


def test_no_msa_number_words():
    msa = ["ثلاث", "ثمان", "عشر ", "مائة", "ثلاثمائة", "خمسة عشر", "ألفان", "اثنان", "اثنين"]
    for src, _ in CASES:
        out = arz.normalize(src)
        for w in msa:
            assert w not in out.replace("عشر تلاف", "").replace("عشر دقايق", ""), (src, out, w)


def test_codeswitch_policies():
    s = "الـ meeting بتاع الـ project اتأجل، ابعتلي الـ PDF للـ manager"
    assert arz.normalize(s, latin="keep") == s
    assert arz.normalize(s, latin="arabic") == "الميتنج بتاع البروجكت اتأجل، ابعتلي البي دي إف للمانجر"
    # unknown lower-case Latin words stay as they are
    assert arz.normalize("جربت الـ blorptastic", latin="arabic") == "جربت الـ blorptastic"
    with pytest.raises(ValueError):
        arz.normalize("x", latin="other")


def test_dispatch_and_cleaning():
    assert normalize("الساعة 7:30 😀", "ar") == "الساعة سبعة ونص"
    with pytest.raises(ValueError):
        normalize("x", "de")


def test_cardinal_range_is_total():
    # every number up to 10**6 spells to words without digits or empty parts
    import random
    rng = random.Random(0)
    for n in [rng.randrange(0, 10**7) for _ in range(3000)] + list(range(0, 1200)):
        w = arz.cardinal(n)
        assert w and not any(c.isdigit() for c in w) and "  " not in w
