"""Every number, generated table and figure of the BA paper, read from BA/eval/results/.

Run:  python3 BA/paper/scripts/make_assets.py      (standard library + numpy + matplotlib)
Writes BA/paper/generated/numbers.tex (\\R{key} macros), generated/tab_*.tex and figures/*.pdf.
Nothing in the paper's text is typed by hand: a missing key prints as a bold ?? in the PDF and is listed by build.sh.
"""
