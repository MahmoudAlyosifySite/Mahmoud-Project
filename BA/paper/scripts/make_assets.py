# ---------------------------------------------------------------- three seeds, held-out (uncertainty.json)
un = load("uncertainty.json")
SEEDSYS = [("ba", "\\BA"), ("voxcpm2", "VoxCPM2 (plain)"), ("namaa", "NAMAA"), ("cb-v3", "Chatterbox V3")]
METS = [("cer_best", f3), ("sim_ecapa", f3), ("c1", pct), ("c2", pct), ("mos_p808", f2)]
rows = []
for cond, cname in [("egy_main", "Held-out Egyptian (24 texts $\\times$ 3 voices)"), ("egy_digits", "Held-out Egyptian with digits (6 $\\times$ 3)")]:
    rows.append(f"\\multicolumn{{6}}{{@{{}}l}}{{\\emph{{{cname}}}}}\\\\")
    for s, nm in SEEDSYS:
        x = un["three_seeds"].get(s, {}).get(cond)
        if not x:
            continue
        cells = []
        for m, fm in METS:
            t = x["metrics"][m]["three_seed"]
            cells.append(f"{fm(t['mean'])} {{\\scriptsize[{fm(t['lo'])}, {fm(t['hi'])}]}}".replace("\\%", "") if fm is pct
                         else f"{fm(t['mean'])} {{\\scriptsize[{fm(t['lo'])}, {fm(t['hi'])}]}}")
            put(f"s3:{s}:{cond}:{m}", fm(t["mean"]))
            put(f"s3:{s}:{cond}:{m}:ci", f"[{fm(t['lo'])}, {fm(t['hi'])}]")
        put(f"s3:{s}:{cond}:nseeds", str(len(x["seeds"])))
        rows.append(f"{nm} & " + " & ".join(cells) + " \\\\")
write("tab_seeds.tex", "\\begin{tabular}{@{}lccccc@{}}\n\\toprule\n"
      "System & CER & ECAPA & Egyptian clf.~1 (\\%) & Egyptian clf.~2 (\\%) & DNSMOS \\\\\n\\midrule\n" + "\n".join(rows) +
      "\n\\bottomrule\n\\end{tabular}\n")
put("s3:nseeds", str(max(len(v["egy_main"]["seeds"]) for v in un["three_seeds"].values())))
for key, t in un["paired_three_seeds"].items():
    a, cond, m = key.split("|")
    fm = pct if m in ("c1", "c2", "failed") else (f2 if m == "mos_p808" else f3)
    tag = f"pt:{a}:{cond}:{m}"
    sgn = lambda v: ("+" if v > 0 else "") + (fm(v) if fm is not pct else f"{100 * v:.0f}")
    put(tag + ":diff", sgn(t["diff"]) + (" points" if fm is pct else ""))
    put(tag + ":ci", f"[{sgn(t['ci_lo'])}, {sgn(t['ci_hi'])}]")
    p = t["p_bootstrap"]
    put(tag + ":p", "p<0.001" if p < 0.001 else f"p={min(p, 1):.3f}")
    if "p_bootstrap_holm_primary6" in t:
        ph = t["p_bootstrap_holm_primary6"]
        put(tag + ":pholm", "p_{\\mathrm{Holm}}<0.001" if ph < 0.001 else f"p_{{\\mathrm{{Holm}}}}={min(ph, 1):.3f}")

