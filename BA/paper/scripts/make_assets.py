R = {}  # key -> LaTeX string


def load(name):
    p = os.path.join(RES, name)
    return json.load(open(p)) if os.path.exists(p) else None


def f3(x):
    return "--" if x is None else f"{x:.3f}"


def f2(x):
    return "--" if x is None else f"{x:.2f}"


def pct(x, nd=0):
    return "--" if x is None else f"{100 * x:.{nd}f}\\%"


def share(x):
    """Share for the selection table: never rounds a non-zero/non-one value to 0% or 100%."""
    if x is None:
        return "--"
    if 0.995 <= x < 1:
        return "$>$99\\%"
    if 0 < x < 0.005:
        return "$<$1\\%"
    return pct(x)


def minus(s):
    return re.sub(r"(?<![\w-])-(?=\d)", r"\\ensuremath{-}", s)


def put(key, val):
    R[key] = minus(str(val))


def write(name, text):
    if re.search(r"(?<!\\)%", text.replace("\\%", "")):
        raise ValueError(f"unescaped % in {name}")
    with open(os.path.join(GEN, name), "w") as f:
        f.write("% generated by scripts/make_assets.py -- do not edit\n" + minus(text))


