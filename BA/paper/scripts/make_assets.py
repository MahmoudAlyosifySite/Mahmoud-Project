"""Every number, generated table and figure of the BA paper, read from BA/eval/results/.

Run:  python3 BA/paper/scripts/make_assets.py      (standard library + numpy + matplotlib)
Writes BA/paper/generated/numbers.tex (\\R{key} macros), generated/tab_*.tex and figures/*.pdf.
Nothing in the paper's text is typed by hand: a missing key prints as a bold ?? in the PDF and is listed by build.sh.
"""
import collections, csv, json, os, re
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.dirname(HERE)
RES = os.path.join(os.path.dirname(PAPER), "eval", "results")
GEN = os.path.join(PAPER, "generated")
FIG = os.path.join(PAPER, "figures")
os.makedirs(GEN, exist_ok=True)
os.makedirs(FIG, exist_ok=True)

R = {}  # key -> LaTeX string


def load(name):
    p = os.path.join(RES, name)
    return json.load(open(p)) if os.path.exists(p) else None


def f3(x):
    return "--" if x is None else f"{x:.3f}"


def f2(x):
    return "--" if x is None else f"{x:.2f}"


def pct(x, nd=0):
    return "--" if x is None else f"{100 * x:.{nd}f}\\%"


def minus(s):
    return re.sub(r"(?<![\w-])-(?=\d)", r"\\ensuremath{-}", s)


def put(key, val):
    R[key] = minus(str(val))


def write(name, text):
    if re.search(r"(?<!\\)%", text.replace("\\%", "")):
        raise ValueError(f"unescaped % in {name}")
    with open(os.path.join(GEN, name), "w") as f:
        f.write("% generated by scripts/make_assets.py -- do not edit\n" + minus(text))


